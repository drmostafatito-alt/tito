#!/usr/bin/env node
/**
 * Generates tests/integration/migrations.generated.ts embedding migrations/*.sql.
 * The vitest workers-pool runs inside workerd (no fs access), so migrations are
 * imported as strings and applied idempotently by the test setup.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";

const files = readdirSync("migrations")
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((f) => {
  const sql = JSON.stringify(readFileSync(`migrations/${f}`, "utf8"));
  return `  { name: ${JSON.stringify(f.replace(/\.sql$/, ""))}, sql: ${sql} }`;
});

const out = `// GENERATED by scripts/gen-migrations-manifest.mjs — do not edit.
export interface EmbeddedMigration {
  name: string;
  sql: string;
}
export const MIGRATIONS: EmbeddedMigration[] = [
${entries.join(",\n")},
];
`;

writeFileSync("tests/integration/migrations.generated.ts", out);
console.log(`Embedded ${files.length} migration(s) into tests/integration/migrations.generated.ts`);
